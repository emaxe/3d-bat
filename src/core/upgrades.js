// Случайные n неповторяющихся улучшений (детерминированный rng).
export function pickUpgrades(pool, rng, n = 3) {
  const copy = [...pool];
  const out = [];
  while (copy.length && out.length < n) {
    const i = Math.floor(rng() * copy.length);
    out.push(copy.splice(i, 1)[0]);
  }
  return out;
}
